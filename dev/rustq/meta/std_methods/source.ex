defmodule RustQ.Meta.StdMethods.Source do
  @moduledoc false
  # Derives `RustQ.Meta.StdMethods` from the Rust standard library's source, which rustup
  # installs as the `rust-src` component. `mix rustq.std` writes the result.

  alias RustQ.Syn
  alias RustQ.Syn.Type

  @path "lib/rustq/meta/std_methods.ex"
  @iterator_traits ["Iterator", "DoubleEndedIterator"]

  @doc false
  def path, do: @path

  @doc false
  def rust_version! do
    {version, 0} = System.cmd("rustc", ["--version"])
    [_rustc, version | _rest] = String.split(version)
    version
  end

  @doc false
  def library! do
    {sysroot, 0} = System.cmd("rustc", ["--print", "sysroot"])
    library = Path.join(String.trim(sysroot), "lib/rustlib/src/rust/library")

    if File.dir?(library),
      do: library,
      else: raise("Rust std source not found at #{library}; run: rustup component add rust-src")
  end

  @doc false
  def build!(library, version) do
    std = parse(library)
    collections = collections(std)

    """
    # Generated by `mix rustq.std` from the Rust #{version} standard library. Do not edit.
    defmodule RustQ.Meta.StdMethods do
      @moduledoc false
      # Which std methods mutate, wrap, or iterate, derived from std's source.

      @doc "The Rust release whose standard library these facts come from."
      def rust_version, do: #{inspect(version)}

      @doc "Methods of std collections and the types they deref to that take `&mut self`."
      def mutating, do: #{atoms(mutating(std, collections))}

      @doc "Methods of std collections and iterators that return an iterator."
      def iterator, do: #{atoms(iterator(std, collections))}

      @doc "Iterator methods that return an option, or whatever `Try` type their closure returns."
      def iterator_option, do: #{atoms(iterator_option(std))}

      @doc "Methods of `Option` and `Result` that std collections lack."
      def wrapper, do: #{atoms(wrapper(std, collections))}

      @doc "Methods of std collections, their own or of traits they implement."
      def collection, do: #{atoms(collection(std, collections))}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp parse(library) do
    {impls, traits} =
      library
      |> Path.join("{core,alloc,std}/src/**/*.rs")
      |> Path.wildcard()
      |> Enum.reject(&(String.contains?(&1, "/std/src/sys/") or Path.basename(&1) == "tests.rs"))
      |> Task.async_stream(&parse_file/1, timeout: :infinity, ordered: false)
      |> Enum.flat_map(fn {:ok, items} -> items end)
      |> Enum.split_with(&match?(%Syn.Impl{}, &1))

    %{impls: impls, traits: Map.new(traits, &{&1.name, &1})}
  end

  # std uses unstable syntax, which `unstable: true` reads without changing what methods it
  # has or what they take and return.
  defp parse_file(path) do
    case path |> File.read!() |> Syn.parse(unstable: true) do
      {:ok, file} ->
        Syn.impls(file) ++ Syn.traits(file)

      {:error, [error | _errors]} ->
        raise "cannot parse #{path}: #{error.message}; teach native/rustq_nif/src/unstable_syntax.rs its syntax"
    end
  end

  # Collections are the types std both collects into and extends, with the types they deref
  # to, as `Vec` derefs to `[T]`.
  defp collections(std) do
    implementing = fn trait ->
      for impl <- std.impls,
          trait_name(impl) == trait,
          name = target_name(impl),
          into: MapSet.new(),
          do: name
    end

    deref =
      for %{types: types} = impl <- std.impls,
          trait_name(impl) == "Deref",
          {"Target", target} <- types,
          into: %{},
          do: {target_name(impl), type_name(target)}

    implementing.("FromIterator")
    |> MapSet.intersection(implementing.("Extend"))
    |> Enum.map(fn name -> Enum.reject([name, deref[name]], &is_nil/1) end)
  end

  defp mutating(std, collections) do
    collections
    |> Enum.flat_map(&inherent_methods(std, &1))
    |> Enum.filter(&match?([%{name: "self", type_ast: %Type.Ref{mutable: true}} | _], &1.args))
    |> names()
  end

  defp iterator(std, collections) do
    trait_methods =
      for name <- ["IntoIterator" | @iterator_traits],
          method <- std.traits[name].methods,
          iterator?(std, method.returns_ast, std.traits[name]),
          do: method

    collection_methods =
      for method <- Enum.flat_map(collections, &inherent_methods(std, &1)),
          iterator?(std, method.returns_ast, nil),
          do: method

    names(trait_methods ++ collection_methods)
  end

  # Iterator methods that return an option, or the `Try` type their closure returns, as
  # `try_fold` does.
  defp iterator_option(std) do
    @iterator_traits
    |> Enum.flat_map(&std.traits[&1].methods)
    |> Enum.filter(fn method ->
      case method.returns_ast do
        %Type.Option{} -> true
        %Type.Path{name: name} -> "Try" in Map.get(Map.new(method.bounds), name, [])
        _type -> false
      end
    end)
    |> names()
  end

  defp wrapper(std, collections) do
    shared = collections |> Enum.flat_map(&inherent_methods(std, &1)) |> names()

    (inherent_methods(std, ["Option"]) ++ inherent_methods(std, ["Result"]))
    |> Enum.filter(&receiver?/1)
    |> names()
    |> Kernel.--(shared)
  end

  # Containers generic over their elements, as `Vec<T>` is and `String` is not, with the methods
  # of their own and of the traits each of them implements.
  defp collection(std, collections) do
    containers = Enum.filter(collections, &generic?(std, hd(&1)))

    shared_traits =
      containers
      |> Enum.map(&implemented_traits(std, &1))
      |> Enum.reduce(&MapSet.intersection/2)

    containers
    |> Enum.flat_map(&inherent_methods(std, &1))
    |> Kernel.++(Enum.flat_map(shared_traits, &std.traits[&1].methods))
    |> Enum.filter(&receiver?/1)
    |> names()
  end

  defp generic?(std, name) do
    Enum.any?(std.impls, fn impl ->
      trait_name(impl) == "FromIterator" and target_name(impl) == name and
        Enum.any?(impl.target_ast.args, &match?(%Type.Path{name: name} when is_binary(name), &1)) and
        Enum.any?(impl.target_ast.args, &parameter?(impl, &1.name))
    end)
  end

  defp implemented_traits(std, collection) do
    for impl <- std.impls,
        target_name(impl) in collection,
        name = trait_name(impl),
        Map.has_key?(std.traits, name),
        into: MapSet.new(),
        do: name
  end

  # Whether `type` is an iterator: `impl Iterator`, `Self` within an iterator trait, an associated
  # type its trait bounds by `Iterator`, or a type std implements `Iterator` for, given that the
  # type parameters the impl requires to be iterators could be.
  defp iterator?(_std, %Type.ImplTrait{} = type, _trait),
    do: Enum.any?(@iterator_traits, &Type.impl_trait?(type, &1))

  defp iterator?(_std, %Type.Self{}, %Syn.Trait{name: name}), do: name in @iterator_traits

  defp iterator?(_std, %Type.Path{segments: ["Self", type]}, %Syn.Trait{types: types}),
    do: types |> Map.new() |> Map.get(type, []) |> Enum.any?(&(&1 in @iterator_traits))

  defp iterator?(std, %Type.Path{name: name, args: args}, trait) do
    Enum.any?(std.impls, fn impl ->
      trait_name(impl) == "Iterator" and match?(%Type.Path{name: ^name}, impl.target_ast) and
        not parameter?(impl, name) and
        impl.target_ast.args
        |> Enum.zip(args)
        |> Enum.all?(fn {parameter, arg} ->
          not iterator_parameter?(impl, parameter) or maybe_iterator?(std, arg, trait)
        end)
    end)
  end

  defp iterator?(_std, _type, _trait), do: false

  defp iterator_parameter?(impl, %Type.Path{name: name}) do
    impl.bounds
    |> Map.new()
    |> Map.get(name, [])
    |> Enum.any?(&(&1 in @iterator_traits))
  end

  defp iterator_parameter?(_impl, _type), do: false

  # A type argument may be an iterator when it is one, or is generic, as `U::IntoIter` or `I`
  # are, but not when it is a std type that is not.
  defp maybe_iterator?(std, type, trait) do
    iterator?(std, type, trait) or
      case type do
        %Type.Path{segments: [_name]} -> not Enum.any?(std.impls, &(target_name(&1) == type.name))
        %Type.Path{} -> true
        _type -> false
      end
  end

  defp parameter?(impl, name), do: name in impl.type_parameters

  defp inherent_methods(std, targets) do
    for impl <- std.impls,
        is_nil(impl.trait),
        target_name(impl) in targets,
        method <- impl.methods,
        method.visibility == :public,
        do: method
  end

  defp receiver?(method), do: match?([%{name: "self"} | _], method.args)

  # Stable methods std documents and does not mark private with a leading underscore; the rest
  # are unstable or hidden helpers, as `Eq::assert_receiver_is_total_eq` is.
  defp names(methods) do
    for(
      %{docs: [_ | _], name: name, attributes: attributes} <- methods,
      "unstable" not in attributes and not String.starts_with?(name, "_"),
      do: name
    )
    |> Enum.uniq()
    |> Enum.sort()
  end

  # Method names are Rust identifiers, so each is a plain atom literal.
  defp atoms(names), do: "[" <> Enum.map_join(names, ", ", &":#{&1}") <> "]"

  defp trait_name(%Syn.Impl{negative: true}), do: nil
  defp trait_name(%Syn.Impl{trait_ast: %Type.Path{name: name}}), do: name
  defp trait_name(%Syn.Impl{}), do: nil

  defp target_name(%Syn.Impl{target_ast: target} = impl) do
    name = type_name(target)
    if name && not parameter?(impl, name), do: name
  end

  defp type_name(%Type.Slice{}), do: "[T]"
  defp type_name(%Type.Option{}), do: "Option"
  defp type_name(%Type.Result{}), do: "Result"
  defp type_name(%Type.Path{name: name}), do: name
  defp type_name(_type), do: nil
end
